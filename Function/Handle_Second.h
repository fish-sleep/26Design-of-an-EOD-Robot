#ifndef __HANDLE_SECOND_H
#define __HANDLE_SECOND_H

/* ============================================================
 * Handle_Second —— ① 机械臂舵机调试 ② USART3 接收(占位, 暂未启用)
 *
 * 【① 机械臂舵机调试 / 硬件】
 *   ID5 底座回转 -> PE5  TIM9_CH1   (整条臂 180° 转动的那一路)
 *   MG996R 是 180° 舵机: 500us = 软件 0°, 1500us = 中位, 2500us = 180°。
 *
 * 【② USART3 硬件】USART3: PB10 = TX, PB11 = RX, 115200 8N1
 *         (MX_USART3_UART_Init() 已经在 main.c 里调用)
 *
 * 【② 现状】USART3 属于"初始化了但没人用", 中断也还没使能, 所以文件里那个
 *         接收回调现在不会被执行 —— 架子先搭好, 要用时按 Handle_Second.c
 *         文件头的三步 TODO 接通即可。
 * ============================================================ */

#include "main.h"

/* ---------------- 用户可配置开关 ---------------- */

/* 【上电自检模式】
 * ★ 标定完、正式跑车之前, 记得改回 ARM_TEST_MODE_OFF,
 *   否则程序会一直卡在扫描里。 */
#define ARM_TEST_MODE_OFF       0   /* 不自检, 走正常流程 */
#define ARM_TEST_MODE_BASE      1   /* 底座舵机扫描: 找零度用 */

#define ARM_TEST_MODE           ARM_TEST_MODE_BASE

/* ------------------------------------------------ */

/* 【舵机自检】让最下面那一路舵机(ID5 底座回转, PE5/TIM9_CH1)上电自动来回扫描,
 * OLED 实时显示当前脉宽和角度, 用来"肉眼确定零度":
 *     500us = 软件 0° (行程一端) / 1500us = 中位 / 2500us = 软件 180°(另一端)
 *
 * 观察并记录三件事:
 *   ① 500us 时这个关节朝哪边       -> "零度"的实际姿态
 *   ② 脉宽变大时它往哪边转         -> servo.c 里这一路的 dir
 *   ③ 500us / 2500us 会不会顶住    -> 真实行程没这么大就要收 pulse_min/max
 *
 * ★ 内部是死循环, 调用后不会返回 —— 要放在 main() 的最后一步。
 * ★ 只有 ID5 这一路会得到脉冲, 另外 4 路保持不输出(松的), 台架上最安全。
 * ⚠ 想看第二遍: 重新上电或按复位, 不需要按键。 */
void Arm_Test_BaseSweep(void);

/* ---------------- ② USART3(占位) ---------------- */

/* 【初始化】挂起第一次字节接收。
 * ⚠ 调用前必须先使能 USART3 的 NVIC 并补上 USART3_IRQHandler,
 *   否则回调永远不会进来(见 Handle_Second.c 文件头 TODO)。
 * 暂时不用串口3 的话, 不要调它。 */
void Handle_Second_Init(void);

/* 【调试用】读已收到的字节数: 调试器里看不到 static 变量,
 * 想确认"中断到底进没进来"时可以读这个值。 */
uint32_t Handle_Second_GetRxCount(void);

#endif /* __HANDLE_SECOND_H */
